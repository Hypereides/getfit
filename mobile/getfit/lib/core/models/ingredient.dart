class Ingredient {
  final String id;
  final String image;
  final String consistency;
  final String name;
  final String original;
  final int amount;
  final String unit;

  const Ingredient({
    required this.id,
    required this.image,
    required this.consistency,
    required this.name,
    required this.original,
    required this.amount,
    required this.unit,
  });
}
